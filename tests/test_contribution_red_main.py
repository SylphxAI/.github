"""Exercise the production verdict against real Git objects and forge-shaped receipts."""
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest import mock

from test_contribution_policy import POLICY, checker, commit, signed_github


class RedMainContribution(unittest.TestCase):
    def setUp(self):
        work = tempfile.TemporaryDirectory()
        self.addCleanup(work.cleanup)
        self.repo = Path(work.name)
        self.env = dict(os.environ, GIT_AUTHOR_NAME='Kyle Tse', GIT_COMMITTER_NAME='Kyle Tse',
                        GIT_AUTHOR_EMAIL='hi@kylet.se', GIT_COMMITTER_EMAIL='hi@kylet.se',
                        GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL=os.devnull)
        self.git('init', '-qb', 'main')
        self.save('first', 'original', 'Initial file')
        first = self.save('first', 'broken', 'Change first file')
        self.save('second', 'original', 'Add second file')
        second = self.save('second', 'broken', 'Change second file')
        self.base = self.save('unrelated', 'keep me', 'Unrelated trunk advance')
        bot = POLICY['red_main']
        self.builder = {'login': bot['login'], 'id': bot['user_id'], 'type': 'Bot'}
        self.identity = {'name': bot['login'], 'email': bot['commit_email']}
        self.git('switch', '-qc', 'rollback')
        self.git('revert', '--no-edit', first, second, identity=self.identity)
        self.head = self.git('rev-parse', 'HEAD')
        self.red_prefix = second[:9]
        repo = {'id': 7, 'full_name': 'SylphxAI/example', 'default_branch': 'main'}
        self.pr = {'number': 9, 'state': 'open', 'user': self.builder.copy(), 'title': 'revert: two commits',
                   'body': 'Revert two changes.', 'base': {'sha': self.base, 'ref': 'main', 'repo': repo.copy()},
                   'head': {'sha': self.head, 'ref': f'auto-revert/{self.red_prefix}-456-1', 'repo': repo.copy()}}
        self.activity = {'activity_type': 'branch_creation', 'ref': 'refs/heads/' + self.pr['head']['ref'],
                         'before': '0' * 40, 'after': self.head, 'actor': self.builder.copy()}
        self.api = mock.Mock(repository=repo['full_name'], token='')
        self.api.get.side_effect = self.get
        patch = mock.patch.object(checker, 'git_remote', return_value=self.repo.as_uri())
        patch.start()
        self.addCleanup(patch.stop)

    def git(self, *args, identity=None):
        env = self.env.copy()
        if identity:
            for role in ('AUTHOR', 'COMMITTER'):
                env[f'GIT_{role}_NAME'], env[f'GIT_{role}_EMAIL'] = identity['name'], identity['email']
        return subprocess.check_output(['git', '-C', str(self.repo), *args], env=env).decode().strip()

    def save(self, path, value, message, **kwargs):
        (self.repo / path).write_text(value + '\n')
        self.git('add', path)
        self.git('commit', '-qm', message, **kwargs)
        return self.git('rev-parse', 'HEAD')

    def get(self, path):
        if path == 'pulls/9':
            return self.pr
        if path.startswith('activity?'):
            branch_suffix = self.pr['head']['ref'].split('/')[1]
            self.assertEqual(path, f'activity?ref=refs%2Fheads%2Fauto-revert%2F{branch_suffix}'
                                   '&activity_type=branch_creation&per_page=1')
            return [self.activity]
        raise AssertionError(path)

    def point_to(self, head):
        self.pr['head']['sha'] = self.activity['after'] = head

    def verdict(self, **kwargs):
        event = {'pull_request': {'number': 9, 'head': {'sha': self.pr['head']['sha']}}}
        return checker.check_event(self.api, 'pull_request', event, self.pr['head']['sha'], POLICY, **kwargs)

    def test_real_single_and_window_reverts_pass_in_both_scopes(self):
        for head in (self.git('rev-parse', self.head + '^'), self.head):
            self.point_to(head)
            self.assertEqual(self.verdict(), [])
            self.assertEqual(self.verdict(check_pull_text=False), [])
        self.pr['body'] = 'Generated by Codex.'
        self.assertEqual({f['rule'] for f in self.verdict()}, {'generated-trailer', 'tool-authorship'})
        self.assertEqual(self.verdict(check_pull_text=False), [])

    def test_copied_metadata_cannot_replace_an_exact_inverse(self):
        title_and_trailer = self.git('show', '-s', '--format=%B', self.head)
        evil = self.save('unrelated', 'not an inverse', title_and_trailer, identity=self.identity)
        self.point_to(evil)
        self.assertEqual({f['rule'] for f in self.verdict()}, {'unapproved-author', 'unapproved-committer'})

    def test_forged_actor_wrong_push_fork_and_non_revert_ref_fail_closed(self):
        for where, key, value in (
            (self.pr['user'], 'login', 'someone-else[bot]'), (self.pr['user'], 'id', 123),
            (self.pr['user'], 'type', 'User'), (self.pr['head']['repo'], 'id', 8),
            (self.pr['base'], 'ref', 'release'), (self.pr['head'], 'ref', 'update-goldens'),
            (self.activity['actor'], 'id', 123), (self.activity, 'after', 'f' * 40),
            (self.activity, 'activity_type', 'push'),
        ):
            with self.subTest(key=key, value=value):
                previous = where[key]
                where[key] = value
                try:
                    self.assertEqual({f['rule'] for f in self.verdict(check_pull_text=False)},
                                     {'unapproved-author', 'unapproved-committer'})
                finally:
                    where[key] = previous

    def test_target_must_already_exist_at_the_red_trunk_revision(self):
        prefix = self.git('rev-parse', self.base + '~2')[:9]
        self.pr['head']['ref'] = f'auto-revert/{prefix}-456-1'
        self.activity['ref'] = 'refs/heads/' + self.pr['head']['ref']
        self.assertEqual({f['rule'] for f in self.verdict()}, {'unapproved-author', 'unapproved-committer'})

    def test_changed_author_or_committer_refuses_even_with_the_same_tree(self):
        for role, field in [('AUTHOR', 'NAME'), ('AUTHOR', 'EMAIL'), ('COMMITTER', 'EMAIL')]:
            with self.subTest(role=role, field=field):
                identity = self.identity
                env = {**self.env, 'GIT_AUTHOR_NAME': identity['name'], 'GIT_COMMITTER_NAME': identity['name'],
                       'GIT_AUTHOR_EMAIL': identity['email'], 'GIT_COMMITTER_EMAIL': identity['email'],
                       f'GIT_{role}_{field}': 'unknown@example.invalid'}
                message = self.git('show', '-s', '--format=%B', self.head)
                forged = subprocess.check_output(['git', '-C', str(self.repo), 'commit-tree',
                                                  self.head + '^{tree}', '-p', self.head + '^', '-m', message],
                                                 env=env, text=True).strip()
                self.point_to(forged)
                self.assertIn('unapproved-' + role.lower(), {f['rule'] for f in self.verdict()})

    def test_queue_checks_original_and_preserves_existing_verified_squash_lane(self):
        squash = commit(message='revert: two commits')
        squash['commit']['author'] = {'name': self.builder['login'],
                                      'email': f"{self.builder['id']}+{self.builder['login']}@users.noreply.github.com"}
        squash['commit']['committer'] = {'name': 'GitHub', 'email': 'noreply@github.com'}
        remote = signed_github(squash)
        self.api.get.side_effect = lambda path: remote if path == 'commits/' + squash['sha'] else self.get(path)
        originals = checker.range_commits(self.base, self.head, self.api.repository, '')
        with mock.patch.object(checker, 'merge_group_snapshot', return_value=([squash], [(self.pr, originals)], {})):
            self.assertEqual(checker.check_event(self.api, 'merge_group', {'merge_group': {}}, '', POLICY), [])
            self.activity['after'] = 'f' * 40
            self.assertEqual({f['rule'] for f in checker.check_event(
                self.api, 'merge_group', {'merge_group': {}}, '', POLICY)}, {'unapproved-author', 'unapproved-committer'})

    def test_offline_input_has_no_authority_and_unreadable_receipt_fails_closed(self):
        originals = checker.range_commits(self.base, self.head, self.api.repository, '')
        self.assertEqual({f['rule'] for f in checker.evaluate(self.pr, originals, POLICY)},
                         {'unapproved-author', 'unapproved-committer'})
        self.api.get.side_effect = lambda path: self.pr if path == 'pulls/9' else self.not_readable()
        with self.assertRaisesRegex(checker.PolicyError, 'activity unavailable'):
            self.verdict()

    @staticmethod
    def not_readable():
        raise checker.PolicyError('activity unavailable')
