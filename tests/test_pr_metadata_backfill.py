"""Exact-head metadata recovery never creates or replaces code evidence."""
import copy
import importlib.util
import io
import json
from pathlib import Path
import unittest
from unittest import mock
import urllib.error

import yaml

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / '.github/actions/pr-metadata-backfill/pr_metadata_backfill.py'
spec = importlib.util.spec_from_file_location('pr_metadata_backfill', SCRIPT)
backfill = importlib.util.module_from_spec(spec)
spec.loader.exec_module(backfill)
HEAD, BASE, MAIN = 'a' * 40, 'b' * 40, 'c' * 40
POLICY = json.loads(backfill.policy.POLICY.read_text())


def pull(number=7, head=HEAD, body='Validated behavior.'):
    return {'number': number, 'state': 'open', 'title': 'Improve metadata recovery', 'body': body,
            'head': {'sha': head}, 'base': {'sha': BASE, 'ref': 'main'}}


def commit():
    return {'sha': HEAD, 'commit': {'message': 'Improve metadata recovery',
            'author': {'name': 'Kyle Tse', 'email': 'hi@kylet.se'},
            'committer': {'name': 'Kyle Tse', 'email': 'hi@kylet.se'}}}


class FixtureAPI:
    def __init__(self, pulls=None, checks=None):
        self.repository, self.token = 'example/repo', 'fixture-token'
        self.pulls = {pr['number']: pr for pr in (pulls or [pull()])}
        self.check_runs = checks or []
        self.writes = []

    def get(self, path):
        if path.startswith('pulls/'):
            return copy.deepcopy(self.pulls[int(path.split('/')[1])])
        if '/check-runs?' in path:
            return {'check_runs': copy.deepcopy(self.check_runs)}
        raise AssertionError('unexpected API path: ' + path)

    def pages(self, path):
        assert path == 'pulls?state=open'
        return list(copy.deepcopy(self.pulls).values())

    def write(self, method, path, payload):
        self.writes.append((method, path, copy.deepcopy(payload)))
        if method == 'POST':
            row = payload | {'id': 100 + len(self.check_runs), 'app': {'id': 15368}}
            self.check_runs.append(row)
            return copy.deepcopy(row)
        assert method == 'PATCH'
        row = next(row for row in self.check_runs if row.get('id') == int(path.rsplit('/', 1)[1]))
        row.update(payload)
        return copy.deepcopy(row)


class Publishing(unittest.TestCase):
    def publish(self, api, **kwargs):
        with mock.patch.object(backfill.policy, 'range_commits', return_value=[commit()]):
            return backfill.publish(api, 7, HEAD, '123', POLICY, **kwargs)

    def test_good_text_publishes_only_metadata_on_the_exact_head(self):
        api = FixtureAPI()
        result = self.publish(api)
        self.assertEqual(result['status'], 'success')
        self.assertEqual([(m, p) for m, p, _ in api.writes], [('POST', 'check-runs'), ('PATCH', 'check-runs/100')])
        self.assertEqual(api.writes[0][2]['name'], 'pr-metadata')
        self.assertEqual(api.writes[0][2]['head_sha'], HEAD)
        self.assertEqual(api.writes[-1][2]['conclusion'], 'success')
        self.assertNotIn('ci-ok', json.dumps(api.writes))

    def test_bad_text_then_body_only_correction_recovers_without_code_calls(self):
        api = FixtureAPI([pull(body='Generated by an automation tool')])
        self.assertEqual(self.publish(api)['status'], 'failure')
        api.pulls[7]['body'] = 'Validated behavior.'
        with mock.patch.object(backfill.policy, 'range_commits', return_value=[commit()]):
            result = backfill.publish(api, 7, HEAD, '124', POLICY)
        self.assertEqual(result['status'], 'success')
        self.assertEqual([row['conclusion'] for row in api.check_runs], ['failure', 'success'])
        self.assertEqual({row['head_sha'] for row in api.check_runs}, {HEAD})
        self.assertTrue(all(path == 'check-runs' or path.startswith('check-runs/') for _, path, _ in api.writes))
        self.assertNotIn('Generated by', json.dumps(api.writes))

    def test_wrong_head_and_closed_pr_publish_nothing(self):
        for field, value in [('state', 'closed'), ('head', {'sha': 'd' * 40})]:
            pr = pull()
            pr[field] = value
            api = FixtureAPI([pr])
            with self.assertRaises(backfill.policy.PolicyError):
                self.publish(api)
            self.assertEqual(api.writes, [])

    def test_commit_identity_remains_enforced(self):
        item = commit()
        item['commit']['author']['name'] = 'Example'
        api = FixtureAPI()
        with mock.patch.object(backfill.policy, 'range_commits', return_value=[item]):
            result = backfill.publish(api, 7, HEAD, '123', POLICY)
        self.assertEqual(result['status'], 'failure')
        self.assertIn('unapproved-author', api.writes[-1][2]['output']['summary'])

    def test_metadata_change_during_snapshot_or_before_publication_fails(self):
        for reads in [2, 3, 4]:
            api = FixtureAPI()
            original = api.get
            count = 0
            def get(path):
                nonlocal count
                if path.startswith('pulls/'):
                    count += 1
                    if count >= reads:
                        api.pulls[7]['body'] = 'Changed during validation.'
                return original(path)
            api.get = get
            with self.subTest(reads=reads):
                # A change before the snapshot starts is read and validated;
                # changes inside or after it must never post stale green.
                expected = 'success' if reads == 2 else 'failure'
                self.assertEqual(self.publish(api)['status'], expected)

    def test_snapshot_acquisition_failure_is_terminal_failure(self):
        api = FixtureAPI()
        with mock.patch.object(backfill.policy, 'pull_snapshot', side_effect=backfill.policy.PolicyError('unreadable')):
            result = backfill.publish(api, 7, HEAD, '123', POLICY)
        self.assertEqual(result['status'], 'failure')
        self.assertEqual(api.check_runs[0]['status'], 'completed')

    def test_same_run_is_not_written_twice(self):
        api = FixtureAPI()
        self.publish(api)
        self.assertEqual(self.publish(api)['status'], 'already-published')
        self.assertEqual(len(api.writes), 2)

    def test_missing_only_preserves_running_red_and_green_producers(self):
        for status, conclusion in [('queued', None), ('in_progress', None), ('completed', 'failure'), ('completed', 'success')]:
            check = {'name': 'pr-metadata', 'head_sha': HEAD, 'app': {'id': 15368},
                     'status': status, 'conclusion': conclusion}
            api = FixtureAPI(checks=[check])
            self.assertEqual(self.publish(api, missing_only=True)['status'], 'producer-present')
            self.assertEqual(api.writes, [])

    def test_check_with_wrong_head_or_app_is_not_a_producer(self):
        for app, head in [(99, HEAD), (15368, 'd' * 40)]:
            api = FixtureAPI(checks=[{'name': 'pr-metadata', 'head_sha': head, 'app': {'id': app}}])
            self.assertEqual(self.publish(api, missing_only=True)['status'], 'success')

    def test_unknown_post_result_is_never_retried(self):
        api = FixtureAPI()
        api.write = mock.Mock(side_effect=backfill.policy.PolicyError('unknown result'))
        with self.assertRaises(backfill.policy.PolicyError):
            self.publish(api)
        self.assertEqual(api.write.call_count, 1)

    def test_http_write_has_one_request_and_withholds_unknown_error_details(self):
        api = backfill.GitHub('example/repo', 'fixture-token')
        error = urllib.error.URLError('diagnostic fixture-token')
        with mock.patch.object(backfill.urllib.request, 'urlopen', side_effect=error) as request:
            with self.assertRaises(backfill.policy.PolicyError) as caught:
                api.write('POST', 'check-runs', {'head_sha': HEAD, 'name': 'pr-metadata'})
        self.assertEqual(request.call_count, 1)
        self.assertNotIn('fixture-token', str(caught.exception))
        sent = request.call_args.args[0]
        self.assertEqual(sent.method, 'POST')
        self.assertEqual(json.loads(sent.data)['head_sha'], HEAD)


class Backfill(unittest.TestCase):
    def execute(self, api, **kwargs):
        return backfill.run(api, kwargs.pop('event_name', 'workflow_dispatch'),
            {'repository': {'default_branch': 'main'}}, MAIN, kwargs.pop('ref', 'refs/heads/main'),
            '123', POLICY, **kwargs)

    def test_only_default_branch_code_can_publish(self):
        for kwargs in [{'ref': 'refs/heads/change'}, {'event_name': 'pull_request'}]:
            api = FixtureAPI()
            with self.assertRaises(backfill.policy.PolicyError):
                self.execute(api, **kwargs)
            self.assertEqual(api.writes, [])

    def test_explicit_target_requires_both_inputs(self):
        for number, head in [('7', ''), ('', HEAD), ('-7', HEAD), ('7', 'main')]:
            api = FixtureAPI()
            with self.assertRaises(backfill.policy.PolicyError):
                self.execute(api, number=number, head=head)
            self.assertEqual(api.writes, [])

    def test_explicit_dispatch_does_not_scan_or_check_the_default_sha(self):
        api = FixtureAPI()
        api.pages = mock.Mock(side_effect=AssertionError('explicit target must not sweep'))
        with mock.patch.object(backfill.policy, 'range_commits', return_value=[commit()]):
            self.assertEqual(self.execute(api, number='7', head=HEAD)[0]['head'], HEAD)
        self.assertNotIn(MAIN, json.dumps(api.writes))

    def test_sweep_fills_missing_heads_and_preserves_existing_producers(self):
        api = FixtureAPI([pull(7), pull(8, 'd' * 40)])
        api.check_runs = [{'id': 10, 'name': 'pr-metadata', 'head_sha': 'd' * 40,
                           'app': {'id': 15368}, 'status': 'completed', 'conclusion': 'failure'}]
        with mock.patch.object(backfill.policy, 'range_commits', return_value=[commit()]):
            rows = self.execute(api)
        self.assertEqual([(row['pr'], row['status']) for row in rows], [(7, 'success'), (8, 'producer-present')])
        self.assertEqual(len(api.writes), 2)

    def test_sweep_refreshes_a_head_changed_since_open_pr_listing(self):
        api = FixtureAPI([pull(7, 'd' * 40)])
        api.pages = mock.Mock(return_value=[pull(7, HEAD)])
        with mock.patch.object(backfill.policy, 'range_commits', return_value=[commit()]):
            result = self.execute(api)
        self.assertEqual(result[0]['head'], 'd' * 40)
        self.assertEqual(api.writes[0][2]['head_sha'], 'd' * 40)

    def test_check_inventory_follows_all_pages(self):
        api = mock.Mock()
        api.get.side_effect = [{'check_runs': [{'name': 'other'}] * 100},
                              {'check_runs': [{'name': 'pr-metadata', 'head_sha': HEAD, 'app': {'id': 15368}}]}]
        self.assertEqual(len(backfill.checks(api, HEAD)), 1)
        self.assertIn('page=2', api.get.call_args.args[0])


class Workflow(unittest.TestCase):
    def test_trusted_backfill_cannot_run_code_or_join_code_concurrency(self):
        workflow = yaml.safe_load((ROOT / '.github/workflows/pr-metadata-backfill.yml').read_text())
        self.assertEqual(workflow[True]['push']['branches'], ['main'])
        self.assertEqual(set(workflow[True]['workflow_dispatch']['inputs']), {'pull-request', 'expected-head'})
        self.assertEqual(workflow['permissions'], {'contents': 'read', 'pull-requests': 'read', 'checks': 'write'})
        self.assertEqual(workflow['concurrency']['group'], 'pr-metadata-backfill-${{ github.run_id }}')
        self.assertFalse(workflow['concurrency']['cancel-in-progress'])
        self.assertEqual(set(workflow['jobs']), {'metadata-backfill'})
        job = workflow['jobs']['metadata-backfill']
        self.assertIn('github.event.repository.default_branch', job['if'])
        self.assertEqual(job['steps'][0]['with']['ref'], '${{ github.sha }}')
        self.assertNotIn('pull_request', workflow[True])
        self.assertEqual(job['runs-on'], 'sylphx-linux-control')
        self.assertNotIn('ci-ok', json.dumps(workflow))


